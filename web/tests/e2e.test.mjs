// Fixture E2E: real HTTP against the mock API, the shipped page bootstrap
// (app.js) driven with a minimal DOM stand-in, and a golden evidence artifact.
//
// Set ATLAS_UPDATE_EVIDENCE=1 to regenerate docs/evidence/UI-FIXTURE-e2e.*
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { after, before, test } from "node:test";

import { WEB_ROOT, createMockServer } from "../mock-server.mjs";
import { loadProfile, renderView } from "../profile.js";

const EVIDENCE_DIR = join(WEB_ROOT, "..", "docs", "evidence");
const ARTIFACT_HTML = join(EVIDENCE_DIR, "UI-FIXTURE-e2e.html");
const ARTIFACT_JSON = join(EVIDENCE_DIR, "UI-FIXTURE-e2e.json");
const SCENARIOS = [
  ["editor-42", "ready"],
  ["editor-empty", "ready"],
  ["editor-unknown", "not_found"],
  ["fixture-server-error", "error"],
  ["fixture-bad-contract", "contract_error"],
];

let server;
let base;

before(async () => {
  server = createMockServer();
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  base = `http://127.0.0.1:${server.address().port}`;
});

after(() => new Promise((resolve) => server.close(resolve)));

const httpFetch = (path, init) => fetch(new URL(path, base), init);

test("mock server serves the static UI", async () => {
  const page = await httpFetch("/");
  assert.equal(page.status, 200);
  const html = await page.text();
  assert.match(html, /<main id="app"/);
  assert.match(html, /<script type="module" src="\/app.js">/);
  for (const [path, type] of [["/app.js", "javascript"], ["/profile.js", "javascript"], ["/styles.css", "css"]]) {
    const response = await httpFetch(path);
    assert.equal(response.status, 200, path);
    assert.match(response.headers.get("content-type"), new RegExp(type));
  }
  assert.equal((await httpFetch("/mock/editors/editor-42.json")).status, 404, "fixtures only reachable via the API");
});

test("API responses are labeled as fixture data", async () => {
  const response = await httpFetch("/api/editors/editor-42");
  assert.equal(response.status, 200);
  assert.equal(response.headers.get("x-atlas-data-mode"), "fixture");
  assert.equal((await httpFetch("/api/editors/editor-unknown")).status, 404);
  assert.equal((await httpFetch("/api/editors/..%2F..%2Fetc")).status, 400);
});

test("page bootstrap renders loading, then the profile, into #app", async () => {
  const history = [];
  const root = {
    dataset: {},
    attributes: {},
    set innerHTML(value) {
      history.push(value);
    },
    setAttribute(name, value) {
      this.attributes[name] = value;
    },
  };
  const form = { elements: { editor: { value: "" } } };
  globalThis.window = { location: { search: "?editor=editor-42" }, fetch: httpFetch };
  globalThis.document = { getElementById: (id) => ({ app: root, "editor-form": form })[id] };
  try {
    await import(`../app.js?e2e=${Date.now()}`);
  } finally {
    delete globalThis.window;
    delete globalThis.document;
  }
  assert.equal(history.length, 2);
  assert.match(history[0], /data-state="loading"/);
  assert.match(history[1], /FIXTURE DATA[\s\S]*data-editor-id="editor-42"/);
  assert.equal(root.dataset.state, "ready");
  assert.equal(root.attributes["aria-busy"], "false");
  assert.equal(form.elements.editor.value, "editor-42");
});

test("fixture scenarios render end to end and match the committed evidence artifact", async () => {
  const transcript = [];
  const sections = [];
  for (const [editorId, expected] of SCENARIOS) {
    const state = await loadProfile(editorId, httpFetch);
    assert.equal(state.status, expected, editorId);
    const html = renderView(state);
    if (state.dataMode !== undefined) assert.match(html, /FIXTURE DATA/, editorId);
    transcript.push({
      editor_id: editorId,
      request: `GET /api/editors/${editorId}`,
      view_status: state.status,
      data_mode: state.dataMode ?? null,
      rendered_sha256: createHash("sha256").update(html).digest("hex"),
      evidence_blocks: html.split('<details class="evidence"').length - 1,
    });
    sections.push(`<section class="scenario" data-scenario="${editorId}">
<h1 class="scenario-title">Scenario: <code>${editorId}</code> → ${state.status}</h1>
${html}
</section>`);
  }
  const css = readFileSync(join(WEB_ROOT, "styles.css"), "utf8");
  const artifact = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>UI-FIXTURE E2E evidence</title>
<style>${css}
.scenario { max-width: 64rem; margin: 2rem auto; padding: 0 1.5rem; }
.scenario-title { font-size: 1rem; border-bottom: 2px solid #333; }</style></head>
<body>
<p class="banner fixture" style="max-width:60rem;margin:1rem auto">Generated by <code>web/tests/e2e.test.mjs</code> from the fixture mock API. Evidence blocks are expandable.</p>
${sections.join("\n")}
</body></html>
`;
  const summary = `${JSON.stringify({ task: "UI-FIXTURE", development_mode: "fixture", scenarios: transcript }, null, 2)}\n`;

  if (process.env.ATLAS_UPDATE_EVIDENCE === "1") {
    writeFileSync(ARTIFACT_HTML, artifact);
    writeFileSync(ARTIFACT_JSON, summary);
  }
  assert.equal(readFileSync(ARTIFACT_HTML, "utf8"), artifact, "HTML artifact is stale; rerun with ATLAS_UPDATE_EVIDENCE=1");
  assert.equal(readFileSync(ARTIFACT_JSON, "utf8"), summary, "JSON artifact is stale; rerun with ATLAS_UPDATE_EVIDENCE=1");
});
