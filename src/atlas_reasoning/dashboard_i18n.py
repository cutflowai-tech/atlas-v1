CATALOGS = {"en": EN, "ar": AR}


def text(locale: str, key: str, **params: Any) -> str:
    """The plain (unescaped) text of ``key``; an unknown key falls back to English, then to the key itself."""
    template = CATALOGS.get(locale, EN).get(key) or EN.get(key) or key
    return template.format(**{name: "" if value is None else value for name, value in params.items()}) if params else template


def t(locale: str, key: str, **params: Any) -> str:
    """``text`` escaped for HTML content and double-quoted attribute values. Parameters (stored or model text) are escaped with
    ``html.escape(quote=True)``, exactly as the Phase 12-14 fragments always escaped them; the fixed catalog wording keeps its
    apostrophes (every attribute here is double-quoted)."""
    template = CATALOGS.get(locale, EN).get(key) or EN.get(key) or key
    wording = escape(template, quote=False).replace('"', "&quot;")
    if not params:
        return wording
    return wording.format(**{name: escape("" if value is None else str(value), quote=True) for name, value in params.items()})


def has(locale: str, key: str) -> bool:
    return key in CATALOGS.get(locale, {})
